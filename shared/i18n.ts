const STRINGS: Record<Lang, Strings> = { en, sv };

export function strings(lang: Lang | undefined): Strings {
  return STRINGS[lang ?? "en"] ?? en;
}

/** Title for the n-th (0-based) occurrence of a round kind in the plan. */
export function roundTitle(kind: RoundKind, occurrence: number, total: number, lang: Lang) {
  const t = strings(lang);
  const base = t.rounds[kind];
  return total > 1 ? `${base} · ${t.part(occurrence + 1)}` : base;
}

export function titledPlan(plan: RoundKind[], lang: Lang) {
  return plan.map((kind, i) => {
    const occurrence = plan.slice(0, i).filter((k) => k === kind).length;
    const total = plan.filter((k) => k === kind).length;
    return { kind, title: roundTitle(kind, occurrence, total, lang) };
  });
}
